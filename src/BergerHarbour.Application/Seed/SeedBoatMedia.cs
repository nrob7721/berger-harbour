    /// <summary>The boat's seeded photos in order (none for an unknown slug).</summary>
    public static IReadOnlyList<BoatImage> PhotosOf(string slug) =>
        Photos.TryGetValue(slug, out var photos) ? photos.Select(p => BoatImage.Create(Uploads + p.Path, p.Description)).ToList() : [];

    /// <summary>The boat's seeded tags in order (none for an unknown slug).</summary>
    public static IReadOnlyList<string> TagsOf(string slug) => Tags.TryGetValue(slug, out var tags) ? tags : [];
}
